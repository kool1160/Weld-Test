"""Rebuild and independently validate the weld-test STEP deliverables.

The build path is DXF -> ezdxf entity import -> CadQuery/OpenCascade B-Rep
operations -> STEP AP214. No STEP entity text is generated by this script.

Run ``build`` and ``validate`` as separate processes. This makes process exit
the explicit close boundary before the validation process reopens every STEP.
"""

